'use strict';

// Rule catalog. Every rule ships with a positive sample (`bad`) and a negative
// sample (`good`) that the test suite runs through the real scanner, so a rule
// cannot silently rot.
//
// Schema:
//   id        stable identifier used by suppressions and tests
//   title     human readable finding title
//   severity  critical | high | medium | low | info
//   cwe       CWE identifier for triage
//   lang      js | py | html | css | json | yaml | sh | sql | any
//   pattern   RegExp, evaluated on the chosen view
//   view      code (comments stripped) or raw (exact source line)
//   hint      one-line remediation
//   multi     match the whole file instead of one line
//   absent    skip when this RegExp matches the file (used for "missing X" rules)
//   exclude   skip when this RegExp matches the line
//   secretGroup  capture group that must look like a real secret (entropy checked)
//   kinds     limit to specific project categories (default: every category)

